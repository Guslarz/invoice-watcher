"""Generates the docs/reference/ pages from facts collected by `./gradlew docsReference`.

Run by scripts/verify.sh; the generated pages are committed with the change that affects them,
and the Build and analyze workflow fails when they are out of date. Inputs:
- build/docs-reference/modules.json: Gradle modules, descriptions, project dependencies,
- <module>/build/classes/java/main/META-INF/spring-configuration-metadata.json,
- build/docs-reference/cli/*.txt: secret-helper --help output,
- docs/specs/*.md frontmatter: which spec covers which module.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FACTS = ROOT / "build" / "docs-reference"
OUTPUT = ROOT / "docs" / "reference"
HEADER = "<!-- Generated by scripts/gen-reference.py - do not edit, run scripts/verify.sh -->\n\n"
METADATA = Path("build/classes/java/main/META-INF/spring-configuration-metadata.json")


def fail(message):
    raise SystemExit(f"scripts/gen-reference.py: {message}")


def load_modules():
    path = FACTS / "modules.json"
    if not path.exists():
        fail(f"{path.relative_to(ROOT)} is missing - run ./gradlew docsReference first")
    modules = json.loads(path.read_text())
    for module in modules:
        if not module["description"]:
            fail(f"module {module['path']} has no description in its build.gradle.kts")
    return modules


def load_specs():
    """Maps module directory -> list of (spec title, spec file)."""
    by_module = {}
    for path in sorted((ROOT / "docs" / "specs").glob("*.md")):
        text = path.read_text()
        if path.name == "index.md" or not text.startswith("---"):
            continue
        frontmatter = text.split("---", 2)[1]
        title = re.search(r"^title: *(.+)$", frontmatter, re.M).group(1).strip()
        modules = re.search(r"^modules:\n((?: +- .+\n)*)", frontmatter, re.M)
        for module_dir in re.findall(r"- *(\S+)", modules.group(1) if modules else ""):
            by_module.setdefault(module_dir, []).append((title, path.name))
    return by_module


def anchor(name):
    return name.replace(".", "-")


def short_type(java_type):
    return re.sub(r"\b(?:[a-z_][a-z0-9_]*\.)+([A-Z])", r"\1", java_type or "")


def env_var(name):
    return re.sub(r"[.\-]", "_", name).upper()


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def configuration_page(modules, specs):
    sections = []
    for module in modules:
        path = ROOT / module["dir"] / METADATA
        if not path.exists():
            continue
        metadata = json.loads(path.read_text())
        names = [group["name"] for group in metadata.get("groups", [])]
        # Top-level groups are the @ConfigurationProperties prefixes; nested groups are folded in.
        tops = [n for n in names if not any(n.startswith(o + ".") for o in names if o != n)]
        for top in tops:
            properties = [p for p in metadata.get("properties", [])
                          if p["name"].startswith(top + ".")]
            for prop in properties:
                if not prop.get("description"):
                    fail(f"property {prop['name']} has no description - add @param Javadoc "
                         f"to its *Properties record ({module['dir']})")
            group = next(g for g in metadata["groups"] if g["name"] == top)
            sections.append((top, group, module, sorted(properties, key=lambda p: p["name"])))

    lines = [
        "# Configuration properties",
        "",
        "Every property can also be set as an environment variable (shown below each name), which",
        "is how the deployed environments configure the applications.",
        "",
    ]
    for top, group, module, properties in sorted(sections):
        lines += [f"## `{top}` {{ #{anchor(top)} }}", ""]
        if group.get("description"):
            lines += [group["description"], ""]
        covered = specs.get(module["dir"], [])
        where = f"Module `{module['path']}`"
        if covered:
            where += " — specified in " + ", ".join(
                f"[{title}](../specs/{file})" for title, file in covered)
        lines += [where + ".", ""]
        lines += ["| Property | Type | Default | Description |", "|---|---|---|---|"]
        for prop in properties:
            default = prop.get("defaultValue")
            lines.append(
                f"| `{prop['name']}`<br>`{env_var(prop['name'])}` "
                f"| `{cell(short_type(prop.get('type')))}` "
                f"| {'`' + cell(default) + '`' if default is not None else ''} "
                f"| {cell(prop['description'])} |")
        lines.append("")
    return "\n".join(lines)


def cli_page():
    cli = FACTS / "cli"
    root_help = cli / "secret-helper.txt"
    if not root_help.exists():
        fail(f"{root_help.relative_to(ROOT)} is missing - run ./gradlew docsReference first")
    text = root_help.read_text()
    commands = re.findall(r"^  ([a-z][\w-]*)\s", text.split("Commands:", 1)[-1], re.M)
    lines = [
        "# secret-helper",
        "",
        "Usage of the `secret-helper` command-line tool, as printed by `--help`. See",
        "[secret encryption](../specs/secret-encryption.md) for what the commands do.",
        "",
        "```text",
        text.rstrip(),
        "```",
        "",
    ]
    for command in commands:
        path = cli / f"{command}.txt"
        if not path.exists():
            fail(f"no usage for command '{command}' - add it to cliCommands in "
                 "apps/secret-helper-app/build.gradle.kts")
        lines += [f"## {command}", "", "```text", path.read_text().rstrip(), "```", ""]
    return "\n".join(lines)


def modules_page(modules, specs):
    lines = [
        "# Modules",
        "",
        "Gradle modules, registered automatically from every directory under `apps/`, `images/`",
        "and `libs/` that contains a `build.gradle.kts`.",
        "",
        "| Module | Directory | Description | Specs |",
        "|---|---|---|---|",
    ]
    for module in modules:
        covered = ", ".join(f"[{title}](../specs/{file})"
                            for title, file in specs.get(module["dir"], []))
        lines.append(f"| `{module['path']}` | `{module['dir']}` "
                     f"| {cell(module['description'])} | {covered} |")
    lines += ["", "## Dependencies", "", "```mermaid", "flowchart LR"]
    for kind in ("apps", "images", "libs"):
        lines.append(f"  subgraph {kind}")
        for module in modules:
            if module["path"].startswith(f":{kind}:"):
                lines.append(f"    {node(module['path'])}[\"{module['path'].split(':')[-1]}\"]")
        lines.append("  end")
    for module in modules:
        for dependency in module["dependencies"]:
            lines.append(f"  {node(module['path'])} --> {node(dependency)}")
    lines += ["```", ""]
    return "\n".join(lines)


def node(path):
    return re.sub(r"[^A-Za-z0-9]", "_", path.strip(":"))


def write(name, content):
    (OUTPUT / name).write_text(HEADER + content)
    print(f"generated docs/reference/{name}")


modules = load_modules()
specs = load_specs()
write("configuration.md", configuration_page(modules, specs))
write("cli.md", cli_page())
write("modules.md", modules_page(modules, specs))
