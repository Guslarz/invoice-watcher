"""Generates the docs/reference/ pages from facts collected by `./gradlew docsReference`.

Run by scripts/verify.sh; the generated pages are committed with the change that affects them,
and the Build and analyze workflow fails when they are out of date. Inputs:
- <module>/build/docs-reference/module.json: Gradle module, description, project dependencies,
- <module>/build/classes/java/main/META-INF/spring-configuration-metadata.json,
- apps/secret-helper-app/build/docs-reference/cli/*.txt: secret-helper --help output.
"""

import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULE_DIRS = ("apps", "images", "libs")
FACTS = Path("build/docs-reference/module.json")
CLI = ROOT / "apps" / "secret-helper-app" / "build" / "docs-reference" / "cli"
OUTPUT = ROOT / "docs" / "reference"
HEADER = "<!-- Generated by scripts/gen-reference.py - do not edit, run scripts/verify.sh -->\n\n"
METADATA = Path("build/classes/java/main/META-INF/spring-configuration-metadata.json")


def fail(message):
    raise SystemExit(f"scripts/gen-reference.py: {message}")


def load_modules():
    # A module is a directory with a build.gradle.kts; leftover build/ directories of removed
    # modules are skipped.
    module_dirs = [build_file.parent for top in MODULE_DIRS
                   for build_file in (ROOT / top).rglob("build.gradle.kts")]
    if (ROOT / "frontend/build.gradle.kts").is_file():
        module_dirs.append(ROOT / "frontend")
    modules = []
    for module_dir in module_dirs:
        path = module_dir / FACTS
        if not path.exists():
            fail(f"{path.relative_to(ROOT)} is missing - run ./gradlew docsReference first")
        modules.append(json.loads(path.read_text()))
    modules.sort(key=lambda module: module["path"])
    for module in modules:
        if not module["description"]:
            fail(f"module {module['path']} has no description in its build.gradle.kts")
    return modules


def anchor(name):
    return name.replace(".", "-")


def short_type(java_type):
    return re.sub(r"\b(?:[a-z_][a-z0-9_]*\.)+([A-Z])", r"\1", java_type or "")


def property_type(java_type, module_dir):
    if not java_type:
        return ""
    class_file = ROOT / module_dir / "build/classes/java/main" / (java_type.replace(".", "/") + ".class")
    if class_file.exists():
        result = subprocess.run(["javap", str(class_file)], check=True, capture_output=True, text=True)
        if "extends java.lang.Enum<" in result.stdout:
            constants = re.findall(r"^\s+public static final " + re.escape(java_type)
                                   + r" (\w+);$", result.stdout, re.M)
            if not constants:
                fail(f"no enum constants found for {java_type}")
            return " / ".join(constant.lower().replace("_", "-") for constant in constants)
    return short_type(java_type)


def env_var(name):
    return re.sub(r"[.\-]", "_", name).upper()


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def configuration_page(modules):
    sections = {}
    hints = {}
    declarations = {}
    for module in modules:
        path = ROOT / module["dir"] / METADATA
        if not path.exists():
            continue
        metadata = json.loads(path.read_text())
        for hint in metadata.get("hints", []):
            values = hints.setdefault(hint["name"], {})
            for value in hint.get("values", []):
                key = json.dumps(value["value"], sort_keys=True)
                if key in values and values[key] != value:
                    fail(f"conflicting value hints for {hint['name']}")
                values[key] = value
        names = [group["name"] for group in metadata.get("groups", [])]
        tops = [n for n in names if not any(n.startswith(o + ".") for o in names if o != n)]
        for top in tops:
            group = next(g for g in metadata["groups"] if g["name"] == top)
            section = sections.setdefault(top, {"group": group, "modules": set(), "properties": {}})
            section["modules"].add(module["path"])
            for prop in metadata.get("properties", []):
                if not prop["name"].startswith(top + "."):
                    continue
                if not prop.get("description"):
                    fail(f"property {prop['name']} has no description - add @param Javadoc "
                         f"to its *Properties record ({module['dir']})")
                previous = declarations.get(prop["name"])
                if previous:
                    for field in ("type", "defaultValue", "description", "deprecation"):
                        if previous.get(field) != prop.get(field):
                            fail(f"conflicting metadata for {prop['name']} ({field})")
                declarations[prop["name"]] = prop
                section["properties"][prop["name"]] = (prop, module)

    lines = [
        "# Configuration properties", "",
        "Every property can also be set as an environment variable (shown below each name), which",
        "is how the deployed environments configure the applications.", "",
        "Suggested values are merged from implementation metadata. They support configuration",
        "assistance; active capabilities validate that a selected implementation is available.", "",
    ]
    for top, section in sorted(sections.items()):
        group = section["group"]
        lines += [f"## `{top}` {{ #{anchor(top)} }}", ""]
        if group.get("description"):
            lines += [group["description"], ""]
        lines += ["Modules: " + ", ".join(f"`{name}`" for name in sorted(section["modules"])) + ".", ""]
        lines += ["| Property | Type | Default | Suggested values | Description |",
                  "|---|---|---|---|---|"]
        for name, (prop, module) in sorted(section["properties"].items()):
            default = prop.get("defaultValue")
            values = " / ".join("`" + cell(item["value"]) + "`"
                                for _, item in sorted(hints.get(name, {}).items()))
            lines.append(
                f"| `{name}`<br>`{env_var(name)}` "
                f"| `{cell(property_type(prop.get('type'), module['dir']))}` "
                f"| {'`' + cell(default) + '`' if default is not None else ''} "
                f"| {values} | {cell(prop['description'])} |")
        lines.append("")
    return "\n".join(lines)


def cli_page():
    cli = CLI
    root_help = cli / "secret-helper.txt"
    if not root_help.exists():
        fail(f"{root_help.relative_to(ROOT)} is missing - run ./gradlew docsReference first")
    text = root_help.read_text()
    commands = re.findall(r"^  ([a-z][\w-]*)\s", text.split("Commands:", 1)[-1], re.M)
    lines = [
        "# secret-helper",
        "",
        "Usage of the `secret-helper` command-line tool, as printed by `--help`.",
        "",
        "```text",
        text.rstrip(),
        "```",
        "",
    ]
    for command in commands:
        path = cli / f"{command}.txt"
        if not path.exists():
            fail(f"no usage for command '{command}' - add it to cliCommands in "
                 "apps/secret-helper-app/build.gradle.kts")
        lines += [f"## {command}", "", "```text", path.read_text().rstrip(), "```", ""]
    return "\n".join(lines)


def modules_page(modules):
    lines = [
        "# Modules",
        "",
        "Gradle modules, registered automatically from every directory under `apps/`, `images/`",
        "and `libs/` that contains a `build.gradle.kts`.",
        "",
        "| Module | Directory | Description |",
        "|---|---|---|",
    ]
    for module in modules:
        lines.append(f"| `{module['path']}` | `{module['dir']}` "
                     f"| {cell(module['description'])} |")
    lines += ["", "## Dependencies", "", "Click the diagram to enlarge it.", "",
              # The default layout places the layer subgraphs side by side; elk stacks them
              # (registered by docs/javascripts/mermaid.mjs).
              "```mermaid", "---", "config:", "  layout: elk", "---", "flowchart TB"]
    for group in ("images", "apps", "impl", "api"):
        lines.append(f"  subgraph {group}")
        for module in modules:
            if layer(module["path"]) == group:
                lines.append(f"    {node(module['path'])}[\"{module['path'].split(':')[-1]}\"]")
        lines.append("  end")
    for module in modules:
        for dependency in module["dependencies"]:
            lines.append(f"  {node(module['path'])} --> {node(dependency)}")
    lines += ["```", ""]
    return "\n".join(lines)


def layer(path):
    kind = path.split(":")[1]
    if kind != "libs":
        return kind
    return "api" if path.endswith("-api") else "impl"


def node(path):
    return re.sub(r"[^A-Za-z0-9]", "_", path.strip(":"))


def write(name, content):
    (OUTPUT / name).write_text(HEADER + content)
    print(f"generated docs/reference/{name}")


if __name__ == "__main__":
    modules = load_modules()
    write("configuration.md", configuration_page(modules))
    write("cli.md", cli_page())
    write("modules.md", modules_page(modules))
